# arithematic operators 
"""
1. Addition - '+'
2. Subtraction - '-'
3. Multiplication - '*'
4. Division 
i) Floor division - '//' -> it will give result as integer 
ex: 5//2 - 2 
ii) Normal division - '/' -> it will give result as float value 
ex: 5/2 - 2.5 
iii) modulo division - '%' -> this will give remainder after division 
ex: 5%2 - 1 
-> x % y -> 0 to y - 1 
ex: x % 5 -> 0 to 4 
if x < y , the remainder will be x  

2 ) 5 ( 2 
    4 
=========
    1 <- this result 
5. power - '**' 
ex: 2 ** 3 = 8 
"""
num1 = 5 
num2 = 2 
print(3 * 2 + 4 / 5)
print(num1 + num2)#7 
print(num1 - num2)#3 
print(num1 * num2)#10 
print(num1 / num2)#2.5 
print(num1 // num2)#2 
print(num1 % num2)# 1 
print(num1 ** num2)# 25 